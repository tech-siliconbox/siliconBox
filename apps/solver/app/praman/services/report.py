def build_report(job: FormalJob) -> str:
    result = job.result
    entries = list(result.assertion_results) if result else []
    status = result.status if result else job.status.upper()
    parts = [
        f"<h1>Formal verification report</h1>",
        f"<div class='muted'>Job <code>{_e(job.job_id)}</code> · run {_e(_when(job.created_at))} · "
        f"report generated {_e(datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC'))}</div>",
        _overview(status, entries, job),
        _settings(job),
        _results(entries, job.solver),
        _traces(job, entries),
        _sources(job),
    ]
    return ("<!doctype html><html lang='en'><head><meta charset='utf-8'>"
            "<meta name='viewport' content='width=device-width,initial-scale=1'>"
            f"<title>Formal verification report · {_e(job.job_id)}</title><style>{_CSS}</style></head>"
            f"<body><main>{''.join(parts)}<footer>Generated by Formal Verify (formalverify.xyz) with "
            f"{_e(_yosys_version())}. Verdicts: "
            + "; ".join(f"<b>{label}</b> {meaning}" for label, _, meaning in VERDICTS.values())
            + ".</footer></main></body></html>")


def _overview(status: str, entries: list[dict], job: FormalJob) -> str:
    counts = Counter(e.get("verdict", "") for e in entries)
    asserts = [e for e in entries if e.get("type") != "COVER"]
    covers = [e for e in entries if e.get("type") == "COVER"]
    cards = [("Properties", len(entries)),
             ("Proven", f"{counts['PROVEN']} / {len(asserts)}"),
             ("Bounded", counts["HOLDS_BOUNDED"]), ("Failing", counts["FAIL"]),
             ("Vacuous", counts["VACUOUS"]),
             ("Covered", f"{sum(1 for e in covers if e.get('verdict') == 'COVERED')} / {len(covers)}"),
             ("Errors", counts["ERROR"] + counts["TIMEOUT"])]
    html = [f"<h2>Result</h2><div><span class='chip' style='background:{_status_colour(status)}'>"
            f"{_e(status)}</span></div>"]
    if job.status == "failed":
        html.append(f"<p>The run stopped before the solvers: </p><pre>{_e(job.error_message)}</pre>")
    html.append("<div class='cards'>" + "".join(
        f"<div class='card'><b>{_e(str(v))}</b><span class='muted'>{k}</span></div>" for k, v in cards) + "</div>")
    return "".join(html)


def _settings(job: FormalJob) -> str:
    result = job.result
    harness = result.harness if result else {}
    sanity = result.sanity if result else {}
    reset = harness.get("signal") or "none"
    if harness.get("signal"):
        reset += f" (active {'low' if harness.get('active_low') else 'high'}, {harness.get('source', '')})"
    clocks = ", ".join(harness.get("clocks", [])) or "none found"
    if harness.get("multiclock"):
        clocks += " (multiclock)"
    rows = [
        ("Mode", job.mode), ("Depth (cycles)", job.depth), ("Solver timeout (s)", job.timeout),
        ("BMC solver", job.solver or "default"),
        ("Top module", job.dut_top or "automatic"),
        ("Reset requested", f"{job.reset_signal or 'automatic'} / polarity {job.reset_polarity}"),
        ("Reset used", reset), ("Clocks", clocks),
        ("Clock for unclocked assertions", job.clock_signal or "automatic"),
        ("Automatic design checks", "on" if job.auto_checks else "off"),
        ("Sanity check", f"{sanity.get('status', '–')}: {sanity.get('message', '')}".rstrip(": ")),
        ("Time", f"compile {job.lowering_time:.1f} s · solvers {job.proving_time:.1f} s · total {job.total_time:.1f} s"),
    ]
    return ("<h2>Run settings</h2><table class='kv'>"
            + "".join(f"<tr><td>{_e(k)}</td><td>{_e(str(v))}</td></tr>" for k, v in rows) + "</table>")


def _results(entries: list[dict], solver: str) -> str:
    if not entries:
        return ""
    # verdicts from the bounded runs carry no engine of their own
    bounded_engine = f"smtbmc {solver}".strip()
    rows = []
    for i, e in enumerate(entries, 1):
        engine = e.get("engine") or ("" if e.get("verdict") in ("ERROR", "TIMEOUT") else bounded_engine)
        bound = "∞" if e.get("verdict") == "PROVEN" else (
            f"step {e['step']}" if e.get("verdict") in TRACED and e.get("step") else
            f"{e['bound']} cycles" if e.get("bound") else "–")
        detail = e.get("verdict_detail") or e.get("message", "")
        if e.get("description"):
            detail = f"{e['description']} — {detail}"
        rows.append(f"<tr><td class='muted'>{i}</td><td class='mono'>{_e(e.get('name', ''))}</td>"
                    f"<td>{_e(e.get('type', '').title())}</td><td>{_chip(e.get('verdict', ''))}</td>"
                    f"<td>{_e(engine or '–')}</td><td>{_e(bound)}</td><td>{_e(detail)}</td></tr>")
    return ("<h2>Properties</h2><table><tr><th>#</th><th>Property</th><th>Type</th><th>Verdict</th>"
            "<th>Engine</th><th>Bound</th><th>Detail</th></tr>" + "".join(rows) + "</table>")


def _traces(job: FormalJob, entries: list[dict]) -> str:
    blocks = []
    for e in entries:
        if e.get("verdict") not in TRACED:
            continue
        selected, vcd_path = resolve_trace(job, e.get("name", ""))
        debug = explain(job, selected, vcd_path) if vcd_path else None
        if not debug or debug.get("error"):
            continue
        title = "Counterexample" if e.get("verdict") == "FAIL" else "Cover witness"
        lines = "".join(f"<li>{_e(line)}</li>" for line in debug.get("explanation", []))
        blocks.append(f"<div class='trace'><h3>{title}: <code>{_e(e['name'])}</code> {_chip(e['verdict'])}</h3>"
                      f"<ol>{lines}</ol>{_wave(debug)}</div>")
    if not blocks:
        return ""
    return ("<h2>Traces</h2><p class='muted'>Each trace is shown through the property: its conditions "
            "(1 = true) and the signals it reads, per clock cycle. The highlighted column is the cycle "
            "of the failure or of the cover.</p>" + "".join(blocks))


def _wave(debug: dict) -> str:
    cycles = debug.get("cycles", [])
    if not cycles:
        return ""
    shown = cycles[-MAX_TRACE_CYCLES:]
    event = debug.get("event_cycle")
    head = "".join(f"<th class='{'ev' if c == event else ''}'>{c}</th>" for c in shown)
    rows = []
    for cond in debug.get("conditions", []):
        cells = "".join(_cell(cond["values"], c, event, condition=True) for c in shown)
        rows.append(f"<tr><td class='name'>{_e(cond['role'])}: {_e(cond['text'])}</td>{cells}</tr>")
    for sig in [*debug.get("signals", []), *debug.get("locals", [])]:
        cells = "".join(_cell(sig["values"], c, event) for c in shown)
        rows.append(f"<tr><td class='name mono'>{_e(sig['name'])}</td>{cells}</tr>")
    note = f"<div class='muted'>Last {len(shown)} of {len(cycles)} cycles.</div>" if len(shown) < len(cycles) else ""
    return f"<div class='wave'>{note}<table><tr><th class='name'>cycle</th>{head}</tr>{''.join(rows)}</table></div>"


def _cell(values: list, cycle: int, event, condition: bool = False) -> str:
    value = values[cycle] if cycle < len(values) else None
    text = "·" if value is None else str(value)
    cls = "ev" if cycle == event else ("hi" if condition and value == 1 else "")
    return f"<td class='{cls}'>{_e(text)}</td>"


def _sources(job: FormalJob) -> str:
    html = ["<h2>Inputs</h2><table class='kv'>"]
    sources = [(f"Design ({job.dut_filename or 'design'})", job.dut_code), ("SVA", job.sva_code)]
    for label, text in sources:
        if text:
            html.append(f"<tr><td>{_e(label)}</td><td class='mono'>sha256 {_sha(text)} · "
                        f"{text.count(chr(10)) + 1} lines</td></tr>")
    html.append("</table>")
    if job.parse_summary:
        html.append(f"<h3>What the tool read</h3><pre>{_e(job.parse_summary)}</pre>")
    for label, text in sources:
        if text:
            html.append(f"<details><summary>{_e(label)} source</summary><pre>{_e(text)}</pre></details>")
    return "".join(html)


def _chip(verdict: str) -> str:
    label, colour, meaning = VERDICTS.get(verdict, (verdict or "–", "#57606a", ""))
    return f"<span class='chip' style='background:{colour}' title='{_e(meaning)}'>{_e(label)}</span>"


def _status_colour(status: str) -> str:
    return {"PASS": "#1a7f37", "FAIL": "#cf222e", "VACUOUS": "#bc4c00"}.get(status, "#9a6700")


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def _when(iso: str) -> str:
    try:
        return datetime.fromisoformat(iso).strftime("%Y-%m-%d %H:%M")
    except ValueError:
        return iso or "–"


@functools.lru_cache(maxsize=1)
def _yosys_version() -> str:
    if shutil.which("yosys") is None:
        return "Yosys (not found)"
    try:
        out = subprocess.run(["yosys", "-V"], capture_output=True, text=True, timeout=10).stdout.strip()
        return out.split(" (")[0] or "Yosys"
    except (OSError, subprocess.TimeoutExpired):
        return "Yosys"


def _e(text: str) -> str:
    return escape(text, quote=True)
