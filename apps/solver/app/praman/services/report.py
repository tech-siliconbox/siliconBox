"""
Verification report: one self-contained HTML file per finished job, for
sign-off and sharing.  It needs nothing once downloaded (inline styles, no
scripts) and prints cleanly, so "Print → Save as PDF" gives the PDF.

Contents: overall result and verdict counts, run settings and what the tool
detected (top, reset, clocks, reader), sanity check, every property with its
verdict, engine and detail, the explained trace of every failure and cover
(the property's conditions and signals per cycle), the compile summary, and
the input sources with their SHA-256.
"""

