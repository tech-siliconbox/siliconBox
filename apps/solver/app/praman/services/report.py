VERDICTS = {   # label, colour, meaning (as in the UI)
    "PROVEN": ("Proven", "#1a7f37", "holds for any number of cycles (full proof)"),
    "HOLDS_BOUNDED": ("Bounded", "#9a6700", "no failure within the depth; not fully proven"),
    "FAIL": ("Fail", "#cf222e", "a counterexample exists"),
    "VACUOUS": ("Vacuous", "#bc4c00", "passes only because its trigger never happens or the assumptions block the design"),
    "COVERED": ("Covered", "#1a7f37", "the scenario can happen"),
    "UNREACHABLE": ("Unreachable", "#57606a", "proven impossible"),
    "NOT_REACHED": ("Not reached", "#9a6700", "not reached within the depth"),
    "ERROR": ("Error", "#cf222e", "not checkable, or a tool problem"),
    "TIMEOUT": ("Timeout", "#9a6700", "the solver ran out of time"),
}
TRACED = {"FAIL", "COVERED"}
MAX_TRACE_CYCLES = 48   # wider traces show their last cycles (the event is at the end)

